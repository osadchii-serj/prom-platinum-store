"""Запуск предварительного просмотра цен: только чтение, без изменения магазина."""

import argparse
from decimal import Decimal

from dotenv import load_dotenv
from rich.console import Console

from prom.безопасность.переменные_окружения import ХранилищеПеременныхОкружения
from prom.подключения.настройки import НастройкиПодключения
from prom.подключения.подключение_prom import ПодключениеProm
from prom.цены.источник_prom import ИсточникТоваровProm
from prom.цены.массовое_обновление_цен import МассовоеОбновлениеЦен
from prom.цены.параметры_наценки import разобрать_процент
from prom.цены.предпросмотр_цен import показать_план


def получить_процент() -> Decimal:
    """Получить процент из аргумента либо запросить у пользователя."""
    парсер = argparse.ArgumentParser(description="Предварительный просмотр наценки Prom.ua")
    парсер.add_argument("--процент", help="Процент наценки, например 20 или 12.5")
    аргументы = парсер.parse_args()
    if аргументы.процент is None:
        try:
            значение = input("Введите процент наценки (например, 20): ")
        except EOFError as ошибка:
            парсер.error("Не указан процент. Передайте --процент 20")
            raise AssertionError("Недостижимо") from ошибка
    else:
        значение = аргументы.процент
    try:
        return разобрать_процент(значение)
    except ValueError as ошибка:
        парсер.error(str(ошибка))
        raise AssertionError("Недостижимо") from ошибка


def main() -> None:
    процент = получить_процент()
    load_dotenv()
    подключение = ПодключениеProm(
        НастройкиПодключения("PROM_API_TOKEN"),
        ХранилищеПеременныхОкружения(),
    )
    источник = ИсточникТоваровProm(подключение)
    план = МассовоеОбновлениеЦен(источник, процент=процент).подготовить_изменения()
    показать_план(план, Console(), процент=процент)


if __name__ == "__main__":
    main()
