"""Точка входа в консоль магазина PLATINUM STORE."""

from dotenv import load_dotenv
from rich.console import Console

from prom.безопасность.переменные_окружения import ХранилищеПеременныхОкружения
from prom.консоль.панель_магазина import показать_панель_магазина
from prom.магазины.магазин import МагазинProm
from prom.подключения.настройки import НастройкиПодключения
from prom.подключения.подключение_prom import ПодключениеProm


def main() -> None:
    """Создать магазин и автоматически проверить подключение."""
    load_dotenv()
    консоль = Console()

    магазин = МагазинProm(
        идентификатор="platinum-store",
        название="PLATINUM STORE",
        подключение=ПодключениеProm(
            настройки=НастройкиПодключения(имя_переменной_токена="PROM_API_TOKEN"),
            хранилище=ХранилищеПеременныхОкружения(),
        ),
    )

    результат = магазин.проверить_подключение()

    показать_панель_магазина(
        консоль=консоль,
        название=магазин.название,
        подключён=результат.успешно,
    )


if __name__ == "__main__":
    main()
