"""Локальное создание и утверждение плана импорта; POST отсутствует."""

from __future__ import annotations

import argparse
from pathlib import Path

from prom.сценарии.план_файлового_импорта import (
    прочитать_план,
    создать_план,
    сохранить_план,
    утвердить_план,
)


def main() -> None:
    """Создать проверяемый план или явно утвердить существующий."""
    парсер = argparse.ArgumentParser(description="PROM: локальный план импорта без POST")
    парсер.add_argument("файл", type=Path)
    парсер.add_argument("ключ_снимка")
    парсер.add_argument("ключ_операции")
    парсер.add_argument("--количество", type=int, default=2)
    парсер.add_argument("--снимки", type=Path, default=Path("data/снимки_каталога"))
    парсер.add_argument("--план", type=Path, required=True)
    парсер.add_argument("--утвердить", action="store_true")
    аргументы = парсер.parse_args()
    if аргументы.утвердить:
        существующий = прочитать_план(аргументы.план)
        if существующий.ключ_операции != аргументы.ключ_операции:
            raise PermissionError("Ключ операции не совпадает")
        # Повторная локальная проверка перед утверждением.
        актуальный = создать_план(
            аргументы.файл, аргументы.снимки, аргументы.ключ_снимка,
            аргументы.ключ_операции, аргументы.количество,
        )
        if (
            существующий.sha256 != актуальный.sha256
            or существующий.количество != актуальный.количество
            or существующий.ключ_снимка != актуальный.ключ_снимка
        ):
            raise ValueError("Предпросмотр изменился, утверждение запрещено")
        фраза = input(f"Для утверждения введи: УТВЕРДИТЬ {аргументы.ключ_операции}\n> ")
        утвердить_план(аргументы.план, аргументы.ключ_операции, фраза)
        print("План утверждён локально. POST не выполнялся.")
    else:
        план = создать_план(
            аргументы.файл, аргументы.снимки, аргументы.ключ_снимка,
            аргументы.ключ_операции, аргументы.количество,
        )
        сохранить_план(аргументы.план, план)
        print(f"План создан: {аргументы.план}")
        print(f"Товаров: {план.количество}; SHA-256: {план.sha256}")
        print("Не утверждён. POST запрещён.")


if __name__ == "__main__":
    main()
