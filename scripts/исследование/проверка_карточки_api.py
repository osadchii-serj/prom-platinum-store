"""Rich-проверка одной карточки относительно живого каталога через GET."""

import argparse
from pathlib import Path

import requests
from rich.console import Console

from prom.api.проверка_тестовой_карточки import сверить_с_api
from prom.диагностика.предпросмотр_импорта import проверить_макет
from prom.интерфейс.стиль import заголовок, сообщение, таблица_параметров


def выполнить() -> None:
    парсер = argparse.ArgumentParser(description="Сверка тестовой карточки с API без записи")
    парсер.add_argument("макет", type=Path)
    парсер.add_argument("экспорт", type=Path)
    аргументы = парсер.parse_args()
    вывод = Console()
    заголовок(вывод, "Контроль каталога / только чтение")
    try:
        карточка, ошибки = проверить_макет(аргументы.макет, аргументы.экспорт)
        if ошибки:
            for ошибка in ошибки:
                сообщение(вывод, "ошибка", ошибка)
            raise SystemExit(1)
        сообщение(вывод, "успех", "Локальная проверка пройдена")
        сверка = сверить_с_api(карточка)
    except (ValueError, OSError, IndexError, RuntimeError, requests.RequestException):
        сообщение(вывод, "ошибка", "Сверка не завершена; результаты не подтверждены")
        raise SystemExit(1) from None
    таблица = таблица_параметров()
    таблица.add_row("Проверено товаров через API", str(сверка.просмотрено))
    таблица.add_row("Совпадений", str(len(сверка.совпадения)))
    таблица.add_row("Идентификаторы совпадений", ", ".join(map(str, сверка.совпадения)) or "Нет")
    вывод.print(таблица)
    if сверка.совпадения:
        сообщение(вывод, "ошибка", "Обнаружены совпадения; импорт запрещён")
        raise SystemExit(1)
    сообщение(вывод, "успех", "Совпадений в текущем каталоге API не найдено")
    сообщение(вывод, "внимание", "Запись не выполнялась; импорт остаётся заблокирован")


if __name__ == "__main__":
    выполнить()
