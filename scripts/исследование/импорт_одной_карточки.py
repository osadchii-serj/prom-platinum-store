"""Предпросмотр, повторная сверка и ручное подтверждение одного импорта."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import requests
from rich.console import Console
from rich.prompt import Prompt

from prom.api.импорт_тестовой_карточки import НАСТРОЙКИ, отправить_один_файл, отпечаток
from prom.api.проверка_тестовой_карточки import сверить_с_api
from prom.диагностика.ошибки_http import показать_ошибку_http
from prom.диагностика.предпросмотр_импорта import проверить_макет
from prom.интерфейс.стиль import заголовок, сообщение, таблица_параметров


def выполнить() -> None:
    """Провести подготовку и, по отдельному согласию, выполнить один POST."""
    парсер = argparse.ArgumentParser(description="Контролируемый импорт одной тестовой карточки")
    парсер.add_argument("макет", type=Path)
    парсер.add_argument("экспорт", type=Path)
    парсер.add_argument("--отправить", action="store_true", help="Разрешить запрос подтверждения записи")
    аргументы = парсер.parse_args()
    консоль = Console()
    заголовок(консоль, "Импорт / одна тестовая карточка")
    try:
        карточка, ошибки = проверить_макет(аргументы.макет, аргументы.экспорт)
        if ошибки:
            for описание in ошибки:
                сообщение(консоль, "ошибка", описание)
            raise SystemExit(1)
        if карточка.get("Код_товару") != "PROM-TEST-20261022-001":
            raise ValueError("Разрешён только согласованный тестовый артикул")
        if карточка.get("Унікальний_ідентифікатор", "").strip():
            raise ValueError("Для нового товара уникальный идентификатор должен быть пустым")
        if карточка.get("Одиниця_виміру", "").strip() != "шт.":
            raise ValueError("Для тестовой карточки требуется единица измерения шт.")
        сверка = сверить_с_api(карточка)
        if сверка.совпадения:
            raise ValueError("В текущем каталоге обнаружены совпадения; запись запрещена")
        исходный_отпечаток = отпечаток(аргументы.макет)
    except (ValueError, OSError, IndexError, RuntimeError, TypeError, requests.RequestException) as ошибка:
        сообщение(консоль, "ошибка", f"Проверка прервана: {ошибка}")
        raise SystemExit(1) from None
    таблица = таблица_параметров()
    таблица.add_row("Магазин", "PLATINUM STORE")
    таблица.add_row("Артикул", карточка["Код_товару"])
    таблица.add_row("Название", карточка.get("Назва_позиції", ""))
    таблица.add_row("Цена", карточка.get("Ціна", ""))
    таблица.add_row("Единица измерения", карточка.get("Одиниця_виміру", ""))
    таблица.add_row("Уникальный ID", "Не задан · создаётся новая карточка")
    таблица.add_row("Наличие", карточка.get("Наявність", ""))
    таблица.add_row("Просмотрено через API", str(сверка.просмотрено))
    таблица.add_row("Совпадений", "0")
    таблица.add_row("SHA-256", исходный_отпечаток)
    таблица.add_row("Настройки", json.dumps(НАСТРОЙКИ, ensure_ascii=False))
    консоль.print(таблица)
    сообщение(консоль, "внимание", "Формат создания и статус публикации не подтверждены серверным испытанием")
    if not аргументы.отправить:
        сообщение(консоль, "успех", "Предпросмотр завершён. Запись не выполнялась")
        return
    подтверждение = Prompt.ask("Для ОДНОГО импорта введи: СОЗДАТЬ ОДНУ ТЕСТОВУЮ КАРТОЧКУ", default="")
    if подтверждение != "СОЗДАТЬ ОДНУ ТЕСТОВУЮ КАРТОЧКУ":
        сообщение(консоль, "внимание", "Операция отменена")
        return
    if отпечаток(аргументы.макет) != исходный_отпечаток:
        сообщение(консоль, "ошибка", "Файл изменился после проверки; операция отменена")
        raise SystemExit(1)
    try:
        результат = отправить_один_файл(аргументы.макет)
    except requests.RequestException:
        сообщение(консоль, "ошибка", "Неизвестен результат сетевого запроса. НЕ повторять POST до сверки каталога")
        raise SystemExit(1) from None
    except (OSError, RuntimeError, ValueError):
        сообщение(консоль, "ошибка", "Отправка не завершена; проверь конфигурацию и файл")
        raise SystemExit(1) from None
    консоль.print(f"HTTP-статус: {результат.код}")
    # Не печатаем тело автоматически: оно может содержать неожиданные данные.
    сообщение(консоль, "внимание", "Проверь результат через повторный GET; HTTP-статус не доказывает создание")
    if результат.код >= 400:
        показать_ошибку_http(консоль, результат.код, результат.тело)
        raise SystemExit(1)


if __name__ == "__main__":
    выполнить()
