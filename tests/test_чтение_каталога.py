"""Изолированные тесты пагинации и двух проходов без реальной сети."""

from io import StringIO
from unittest.mock import Mock

import pytest
from rich.console import Console

from prom.сценарии.чтение_каталога import (
    показать_чтение,
    получить_стабильный_снимок,
    прочитать_каталог,
)


def ответ(товары: list[dict[str, object]]) -> Mock:
    результат = Mock()
    результат.json.return_value = {"products": товары}
    return результат


def сессия(*страницы: list[dict[str, object]]) -> Mock:
    соединение = Mock()
    соединение.get.side_effect = [ответ(страница) for страница in страницы]
    return соединение


def тестовый_товар(идентификатор: int, sku: str = "A") -> dict[str, object]:
    return {"id": идентификатор, "sku": sku}


def test_пустой_каталог() -> None:
    снимок, страниц = прочитать_каталог(сессия([]))
    assert снимок.полный and страниц == 1
    assert not снимок.карточки


def test_последняя_короткая_страница() -> None:
    соединение = сессия([тестовый_товар(5), тестовый_товар(4)], [тестовый_товар(3)])
    снимок, страниц = прочитать_каталог(соединение, размер_страницы=2)
    assert страниц == 2
    assert [к.идентификатор for к in снимок.карточки] == [3, 4, 5]
    assert соединение.get.call_args.kwargs["params"]["last_id"] == 4


def test_ровно_полная_страница_требует_проверки_конца() -> None:
    снимок, страниц = прочитать_каталог(
        сессия([тестовый_товар(2), тестовый_товар(1)], []),
        размер_страницы=2,
    )
    assert страниц == 2 and снимок.полный


def test_повтор_id_между_страницами() -> None:
    with pytest.raises(ValueError, match="повторный"):
        прочитать_каталог(
            сессия([тестовый_товар(4), тестовый_товар(3)], [тестовый_товар(3)]),
            размер_страницы=2,
        )


def test_страница_не_двигается_назад() -> None:
    with pytest.raises(ValueError, match="диапазона"):
        прочитать_каталог(
            сессия([тестовый_товар(4), тестовый_товар(3)], [тестовый_товар(5)]),
            размер_страницы=2,
        )


def test_достигнут_лимит() -> None:
    соединение = сессия([тестовый_товар(2)])
    with pytest.raises(RuntimeError, match="предел страниц"):
        прочитать_каталог(соединение, размер_страницы=1, предел_страниц=1)
    assert соединение.get.call_count == 1


def test_неверный_ответ() -> None:
    соединение = Mock()
    соединение.get.return_value.json.return_value = {"other": []}
    with pytest.raises(TypeError, match="products"):
        прочитать_каталог(соединение)


def test_недопустимый_id() -> None:
    with pytest.raises(TypeError, match="ID"):
        прочитать_каталог(сессия([{"id": True}]))


def test_слишком_много_товаров() -> None:
    with pytest.raises(ValueError, match="больше"):
        прочитать_каталог(сессия([тестовый_товар(2), тестовый_товар(1)]), размер_страницы=1)


def test_совпавшие_проходы() -> None:
    соединение = сессия([тестовый_товар(1)], [тестовый_товар(1)])
    итог = получить_стабильный_снимок(соединение=соединение)
    assert итог.стабилен and итог.снимок.полный
    assert итог.страниц_за_проход == (1, 1)


def test_изменение_между_проходами() -> None:
    соединение = сессия([тестовый_товар(1)], [тестовый_товар(2)])
    итог = получить_стабильный_снимок(соединение=соединение)
    assert not итог.стабилен and not итог.снимок.полный


def test_rich_без_содержимого_карточек() -> None:
    соединение = сессия([тестовый_товар(1, "SECRET")], [тестовый_товар(1, "SECRET")])
    итог = получить_стабильный_снимок(соединение=соединение)
    поток = StringIO()
    показать_чтение(итог, консоль=Console(file=поток, force_terminal=False))
    assert "SECRET" not in поток.getvalue()
    assert "Изменение карточек заблокировано" in поток.getvalue()
