"""Проверки безопасной сверки каталога."""

from io import StringIO

import pytest
from rich.console import Console

from prom.сценарии.сверка_каталога import (
    показать_сверку,
    собрать_снимок,
    сопоставить,
)


def товар(ид: int, sku: str | None = None, **поля: object) -> dict[str, object]:
    return {"id": ид, "sku": sku, **поля}


def test_новые_id_не_смешиваются_со_старыми() -> None:
    до = собрать_снимок([товар(1, "A")], полный=True)
    после = собрать_снимок([товар(1, "A"), товар(2, "B")], полный=True)
    итог = сопоставить(до, после)
    assert итог.новые_id == (2,)
    assert not итог.разрешено_изменение


def test_повторные_sku_не_скрывают_новый_id() -> None:
    до = собрать_снимок([товар(1, "A")], полный=True)
    после = собрать_снимок([товар(1, "A"), товар(2, "A")], полный=True)
    итог = сопоставить(до, после)
    assert итог.новые_id == (2,)
    assert итог.неоднозначные_sku == ("A",)


def test_изменение_старой_карточки() -> None:
    до = собрать_снимок([товар(1, "A")], полный=True)
    после = собрать_снимок([товар(1, "B")], полный=True)
    assert сопоставить(до, после).изменённые_id == (1,)


def test_удаление() -> None:
    до = собрать_снимок([товар(1), товар(2)], полный=True)
    после = собрать_снимок([товар(2)], полный=True)
    assert сопоставить(до, после).удалённые_id == (1,)


def test_неполный_снимок_блокирует_доверие() -> None:
    до = собрать_снимок([товар(1)], полный=False)
    после = собрать_снимок([товар(2)], полный=True)
    assert not сопоставить(до, после).допустим_предпросмотр


@pytest.mark.parametrize(
    ("ид", "исключение"),
    [
        (0, ValueError),
        (-1, ValueError),
        (True, TypeError),
        ("1", TypeError),
        (None, TypeError),
    ],
)
def test_невалидные_id(ид: object, исключение: type[Exception]) -> None:
    with pytest.raises(исключение):
        собрать_снимок([{"id": ид}], полный=True)


def test_повторный_id_ошибка() -> None:
    with pytest.raises(ValueError):
        собрать_снимок([товар(1), товар(1)], полный=True)


def test_неверный_sku_ошибка() -> None:
    with pytest.raises(TypeError):
        собрать_снимок([{"id": 1, "sku": 23}], полный=True)


def test_rich_не_выводит_артикулы() -> None:
    до = собрать_снимок([], полный=True)
    после = собрать_снимок([товар(2, "СЕКРЕТНЫЙ-АРТИКУЛ")], полный=True)
    буфер = StringIO()
    показать_сверку(сопоставить(до, после), консоль=Console(file=буфер, force_terminal=False))
    assert "ЗАПРЕЩЕНО" in буфер.getvalue()
    assert "СЕКРЕТНЫЙ-АРТИКУЛ" not in буфер.getvalue()
