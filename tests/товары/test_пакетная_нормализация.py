"""Проверки этапа 0.2."""

from prom.товары.пакетная_нормализация import нормализовать_пакет


def карточка(идентификатор: str) -> dict[str, object]:
    return {"external_id": идентификатор, "name": "Товар", "price": "12,50", "quantity_in_stock": 0}


def test_пустой_пакет() -> None:
    результат = нормализовать_пакет([])
    assert (результат.всего, результат.успешные, результат.ошибки) == (0, (), ())


def test_ошибки_не_прерывают_пакет() -> None:
    результат = нормализовать_пакет([карточка("001"), {"external_id": "2"}, карточка("003"), None])
    assert результат.всего == 4
    assert [запись.номер_строки for запись in результат.успешные] == [1, 3]
    assert [(ошибка.номер_строки, ошибка.поле) for ошибка in результат.ошибки] == [
        (2, "name"),
        (4, "карточка"),
    ]


def test_дубликат_и_повторная_обработка() -> None:
    данные = [карточка("001"), карточка("001"), карточка("002")]
    первый = нормализовать_пакет(данные)
    второй = нормализовать_пакет(данные)
    assert первый == второй
    assert len(первый.успешные) == 2
    assert первый.ошибки[0].поле == "external_id"


def test_тысяча_карточек() -> None:
    результат = нормализовать_пакет(карточка(str(номер)) for номер in range(1000))
    assert результат.всего == 1000
    assert len(результат.успешные) == 1000
    assert not результат.ошибки
