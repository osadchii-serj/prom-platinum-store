"""Проверки автономной нормализации товарных данных."""

from decimal import Decimal

import pytest

from prom.товары.нормализация import (
    ОшибкаНормализации,
    нормализовать_идентификатор,
    нормализовать_название,
    нормализовать_остаток,
    нормализовать_товар,
    нормализовать_цену,
)


@pytest.mark.parametrize(
    ("исходное", "ожидаемое"),
    [
        ("100", Decimal(100)),
        (100, Decimal(100)),
        ("1 674,40 грн", Decimal("1674.40")),
        ("1\u00a0674,40 ₴", Decimal("1674.40")),
        ("0.00001", Decimal("0.00001")),
        (1674.4, Decimal("1674.4")),
    ],
)
def test_корректная_цена(исходное: object, ожидаемое: Decimal) -> None:
    assert нормализовать_цену(исходное) == ожидаемое


@pytest.mark.parametrize(
    "исходное",
    [None, True, False, 0, -1, "", "abc", "100 USD", "1,2,3"],
)
def test_ошибочная_цена(исходное: object) -> None:
    with pytest.raises(ОшибкаНормализации):
        нормализовать_цену(исходное)


def test_ведущие_нули_идентификатора() -> None:
    assert нормализовать_идентификатор("000123") == "000123"


def test_нормализация_названия() -> None:
    assert нормализовать_название(" Датчик парковки ") == "Датчик парковки"


@pytest.mark.parametrize(
    "исходное",
    ["", "   ", 123, "А" * 111],
)
def test_ошибочное_название(исходное: object) -> None:
    with pytest.raises(ОшибкаНормализации):
        нормализовать_название(исходное)


@pytest.mark.parametrize(
    ("исходное", "ожидаемое"),
    [
        (None, None),
        ("", None),
        ("0", 0),
        (0, 0),
        ("12", 12),
    ],
)
def test_корректный_остаток(
    исходное: object,
    ожидаемое: int | None,
) -> None:
    assert нормализовать_остаток(исходное) == ожидаемое


@pytest.mark.parametrize(
    "исходное",
    [-1, "1.5", 1.5, True, "неизвестно"],
)
def test_ошибочный_остаток(исходное: object) -> None:
    with pytest.raises(ОшибкаНормализации):
        нормализовать_остаток(исходное)


def test_полная_нормализация_товара() -> None:
    товар = нормализовать_товар(
        {
            "external_id": "000123",
            "name": " Датчик парковки ",
            "price": "1 674,40 грн",
            "quantity_in_stock": "12",
        }
    )

    assert товар.внешний_идентификатор == "000123"
    assert товар.название == "Датчик парковки"
    assert товар.цена == Decimal("1674.40")
    assert товар.остаток == 12
