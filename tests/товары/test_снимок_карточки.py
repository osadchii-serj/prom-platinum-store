"""Локальные проверки сохранения тестовой карточки."""

import json

import pytest

from prom.товары.снимок_карточки import (
    ИДЕНТИФИКАТОР_ТЕСТОВОГО_ТОВАРА,
    получить_карточку,
    сохранить_снимок,
)


def test_снимок_сохраняет_исходные_данные(tmp_path):
    данные = {
        "product": {
            "id": ИДЕНТИФИКАТОР_ТЕСТОВОГО_ТОВАРА,
            "name": "Тест",
        }
    }

    путь = сохранить_снимок(данные, tmp_path)

    assert json.loads(путь.read_text(encoding="utf-8")) == данные


def test_снимок_отклоняет_чужой_товар(tmp_path):
    with pytest.raises(ValueError):
        сохранить_снимок({"id": 1}, tmp_path)


def test_запрос_отклоняет_чужой_идентификатор():
    with pytest.raises(ValueError):
        получить_карточку("фиктивный-токен", 1)
