"""Проверки объектной модели магазина без сетевых запросов."""

import pytest

from prom.магазины.магазин import МагазинProm
from prom.подключения.интерфейсы import РезультатПодключения


class ПодключениеЗаглушка:
    def __init__(self) -> None:
        self.вызовы = 0

    def проверить(self) -> РезультатПодключения:
        self.вызовы += 1
        return РезультатПодключения(успешно=True, сообщение="Подключение проверено")


def test_создание_магазина_без_запросов() -> None:
    подключение = ПодключениеЗаглушка()
    магазин = МагазинProm("platinum-store", "PLATINUM STORE", подключение)
    assert магазин.название == "PLATINUM STORE"
    assert подключение.вызовы == 0
    assert магазин.проверить_подключение().успешно
    assert подключение.вызовы == 1


@pytest.mark.parametrize("идентификатор, название", [("", "Магазин"), ("магазин", " ")])
def test_пустые_поля_запрещены(идентификатор: str, название: str) -> None:
    with pytest.raises(ValueError):
        МагазинProm(идентификатор, название, ПодключениеЗаглушка())
