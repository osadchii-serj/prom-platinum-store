"""Локальные тесты без доступа к магазину."""

from prom.диагностика.проверки import уникальные_идентификаторы


def test_уникальные_идентификаторы():
    assert уникальные_идентификаторы([{"id": 1}, {"id": 2}])


def test_повторные_идентификаторы():
    assert not уникальные_идентификаторы([{"id": 1}, {"id": 1}])


def test_отсутствующий_идентификатор():
    assert not уникальные_идентификаторы([{"sku": "A"}])
