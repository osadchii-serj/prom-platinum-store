"""Проверки защитных барьеров группового исполнителя без сети."""

import hashlib
import json
from pathlib import Path

import pytest

from prom.api.исполнитель_групповых_статусов import (
    ОстановкаОперации,
    проверить_план,
    прочитать_журнал,
    этапы_испытания,
)
from prom.api.план_групповых_статусов import СнимокКарточки, построить_план


def план() -> dict:
    return построить_план([
        СнимокКарточки(3243922294, 'PROM-TEST-20261022-001', 'not_on_display'),
        СнимокКарточки(3244158641, 'PROM-TEST-20261022-002', 'on_display'),
    ])


def test_план_принимается() -> None:
    assert len(проверить_план(план())) == 6


def test_чужой_id_запрещён() -> None:
    данные = план()
    данные['карточки'][0]['идентификатор'] = 999
    with pytest.raises(ValueError):
        проверить_план(данные)


def test_подмена_маршрута_запрещена() -> None:
    данные = план()
    данные['этапы'][0]['в'] = 'deleted'
    with pytest.raises(ValueError):
        проверить_план(данные)


def test_пустой_журнал(tmp_path: Path) -> None:
    assert прочитать_журнал(tmp_path / 'нет.jsonl', 'abc') == []


def test_незавершённый_post_блокирует_повтор(tmp_path: Path) -> None:
    путь = tmp_path / 'журнал.jsonl'
    путь.write_text(json.dumps({'сумма_плана': 'abc', 'номер': 0,
                                 'этап': 'удаление', 'состояние': 'отправка_возможна'}) + '\n')
    with pytest.raises(ОстановкаОперации):
        прочитать_журнал(путь, 'abc')


def test_завершённый_этап_читается(tmp_path: Path) -> None:
    путь = tmp_path / 'журнал.jsonl'
    записи = [{'сумма_плана': 'abc', 'номер': 0, 'этап': 'подготовка_к_удалению',
               'состояние': состояние}
              for состояние in ('отправка_возможна', 'подтверждено')]
    путь.write_text(''.join(json.dumps(запись) + '\n' for запись in записи))
    assert len(прочитать_журнал(путь, 'abc')) == 1


def test_чужой_план_в_журнале(tmp_path: Path) -> None:
    путь = tmp_path / 'журнал.jsonl'
    путь.write_text(json.dumps({'сумма_плана': hashlib.sha256('другой'.encode()).hexdigest()}) + '\n')
    with pytest.raises(ОстановкаОперации):
        прочитать_журнал(путь, 'abc')


def test_групповое_удаление_объединяет_оба_id() -> None:
    этапы = этапы_испытания(план())
    assert len(этапы) == 5
    assert этапы[0]['этап'] == 'подготовка_к_удалению'
    assert этапы[1]['этап'] == 'групповое_удаление'
    assert {п['id'] for п in этапы[1]['запрос']} == {3243922294, 3244158641}
    assert этапы[1]['исходные_статусы'] == {3243922294: 'not_on_display', 3244158641: 'draft'}
    assert этапы[2]['этап'] == 'восстановление'


def test_план_не_меняется_при_объединении() -> None:
    данные = план()
    исходный = json.dumps(данные, sort_keys=True)
    этапы_испытания(данные)
    assert json.dumps(данные, sort_keys=True) == исходный
