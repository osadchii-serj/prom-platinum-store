"""Проверки предпросмотра двух закреплённых тестовых карточек."""

import pytest

from prom.api.план_групповых_статусов import (
    СнимокКарточки,
    извлечь_снимок,
    построить_план,
)


def карточки(статус_1: str, статус_2: str) -> list[СнимокКарточки]:
    return [
        СнимокКарточки(3243922294, "PROM-TEST-20261022-001", статус_1),
        СнимокКарточки(3244158641, "PROM-TEST-20261022-002", статус_2),
    ]


def test_скрытая_и_опубликованная_карточки() -> None:
    план = построить_план(карточки("not_on_display", "on_display"))
    assert план["режим"] == "ТОЛЬКО_ПРОСМОТР_БЕЗ_POST"
    assert [шаг["этап"] for шаг in план["этапы"]] == [
        "подготовка_к_удалению", "удаление_из_draft", "удаление_скрытых",
        "восстановление", "возврат_черновиков", "возврат_публикации",
    ]
    assert len(next(шаг for шаг in план["этапы"] if шаг["этап"] == "восстановление")["запрос"]) == 2
    assert plan_ids(план) == {3243922294, 3244158641}


def plan_ids(план: dict) -> set[int]:
    return {строка["id"] for шаг in план["этапы"] for строка in шаг["запрос"]}


def test_два_черновика() -> None:
    план = построить_план(карточки("draft", "draft"))
    assert [шаг["этап"] for шаг in план["этапы"]] == [
        "удаление_из_draft", "восстановление", "возврат_черновиков",
    ]


@pytest.mark.parametrize("статус", ["deleted", "other", ""])
def test_недопустимые_статусы(статус: str) -> None:
    with pytest.raises(ValueError):
        построить_план(карточки("draft", статус))


def test_подмена_id_блокируется() -> None:
    список = карточки("draft", "on_display")
    список[1] = СнимокКарточки(123, список[1].артикул, "on_display")
    with pytest.raises(ValueError):
        построить_план(список)


def test_подмена_sku_блокируется() -> None:
    with pytest.raises(ValueError):
        извлечь_снимок({"product": {"id": 1, "sku": "wrong", "status": "draft"}}, 1, "ok")


def test_неверный_тип_ответа() -> None:
    with pytest.raises(TypeError):
        извлечь_снимок({"product": []}, 1, "ok")


def test_повтор_id_блокируется() -> None:
    список = карточки("draft", "draft")
    список[1] = СнимокКарточки(список[0].идентификатор, список[1].артикул, "draft")
    with pytest.raises(ValueError):
        построить_план(список)
