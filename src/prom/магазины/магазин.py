"""Объект магазина и делегирование операций подключению."""

from prom.подключения.интерфейсы import ИнтерфейсПодключения, РезультатПодключения


class МагазинProm:
    def __init__(
        self, идентификатор: str, название: str, подключение: ИнтерфейсПодключения
    ) -> None:
        if not идентификатор.strip() or not название.strip():
            raise ValueError("Идентификатор и название магазина обязательны")
        self.идентификатор = идентификатор
        self.название = название
        self.подключение = подключение

    def проверить_подключение(self) -> РезультатПодключения:
        return self.подключение.проверить()
