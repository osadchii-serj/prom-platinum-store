"""Нормализация исходных данных товара без обращения к Prom.ua."""

import re
from dataclasses import dataclass
from decimal import Decimal, InvalidOperation
from typing import Any


class ОшибкаНормализации(ValueError):
    """Входное значение невозможно безопасно нормализовать."""


@dataclass(frozen=True, slots=True)
class НормализованныйТовар:
    """Минимальная внутренняя модель товара."""

    внешний_идентификатор: str
    название: str
    цена: Decimal
    остаток: int | None


def нормализовать_идентификатор(значение: Any) -> str:
    """Сохранить идентификатор как строку."""

    if isinstance(значение, bool) or значение is None:
        raise ОшибкаНормализации("external_id: отсутствует идентификатор")

    if not isinstance(значение, (str, int)):
        raise ОшибкаНормализации("external_id: ожидается строка или целое число")

    результат = str(значение).strip()
    if not результат:
        raise ОшибкаНормализации("external_id: пустой идентификатор")

    return результат


def нормализовать_название(значение: Any) -> str:
    """Убрать крайние пробелы и проверить название."""

    if not isinstance(значение, str):
        raise ОшибкаНормализации("name: ожидается строка")

    результат = значение.strip()

    if not результат:
        raise ОшибкаНормализации("name: пустое название")

    if len(результат) > 110:
        raise ОшибкаНормализации("name: превышено 110 символов")

    return результат


def нормализовать_цену(значение: Any) -> Decimal:
    """Привести число или текстовую цену к Decimal."""

    if isinstance(значение, bool) or значение is None:
        raise ОшибкаНормализации("price: отсутствует корректная цена")

    if not isinstance(значение, (str, int, float, Decimal)):
        raise ОшибкаНормализации("price: неподдерживаемый тип")

    текст = str(значение).strip()

    # Удаляем только явно распознанное обозначение гривны.
    текст = re.sub(r"\s*(?:грн|₴)\s*$", "", текст, flags=re.IGNORECASE)
    текст = текст.replace("\u00a0", "").replace("\u202f", "")
    текст = текст.replace(" ", "").replace(",", ".")

    if not re.fullmatch(r"\d+(?:\.\d+)?", текст):
        raise ОшибкаНормализации("price: неверный формат цены")

    try:
        результат = Decimal(текст)
    except InvalidOperation as ошибка:
        raise ОшибкаНормализации("price: неверное число") from ошибка

    if not результат.is_finite() or результат <= 0:
        raise ОшибкаНормализации("price: цена должна быть положительной")

    return результат


def нормализовать_остаток(значение: Any) -> int | None:
    """Различать отсутствие остатка и нулевой остаток."""

    if значение is None or значение == "":
        return None

    if isinstance(значение, bool):
        raise ОшибкаНормализации("quantity_in_stock: неверный тип")

    if isinstance(значение, int):
        результат = значение
    elif isinstance(значение, str) and re.fullmatch(r"\d+", значение.strip()):
        результат = int(значение.strip())
    else:
        raise ОшибкаНормализации("quantity_in_stock: ожидается неотрицательное целое число")

    if результат < 0:
        raise ОшибкаНормализации("quantity_in_stock: отрицательный остаток")

    return результат


def нормализовать_товар(
    данные: dict[str, Any],
) -> НормализованныйТовар:
    """Преобразовать одну исходную запись во внутреннюю модель."""

    return НормализованныйТовар(
        внешний_идентификатор=нормализовать_идентификатор(данные.get("external_id")),
        название=нормализовать_название(данные.get("name")),
        цена=нормализовать_цену(данные.get("price")),
        остаток=нормализовать_остаток(данные.get("quantity_in_stock")),
    )
