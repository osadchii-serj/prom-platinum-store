"""Независимая пакетная нормализация без сетевых запросов и записи данных."""

from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Any

from prom.товары.нормализация import НормализованныйТовар, ОшибкаНормализации, нормализовать_товар


@dataclass(frozen=True, slots=True)
class ОшибкаКарточки:
    номер_строки: int
    поле: str
    причина: str
    исходные_данные: object


@dataclass(frozen=True, slots=True)
class УспешнаяКарточка:
    номер_строки: int
    товар: НормализованныйТовар
    исходные_данные: Mapping[str, Any]


@dataclass(frozen=True, slots=True)
class РезультатПакета:
    всего: int
    успешные: tuple[УспешнаяКарточка, ...]
    ошибки: tuple[ОшибкаКарточки, ...]


def нормализовать_пакет(карточки: Iterable[object]) -> РезультатПакета:
    """Отклонять повторный ID; первая успешно обработанная карточка имеет приоритет."""
    успешные: list[УспешнаяКарточка] = []
    ошибки: list[ОшибкаКарточки] = []
    идентификаторы: dict[str, int] = {}
    всего = 0
    for номер, исходное in enumerate(карточки, start=1):
        всего = номер
        if not isinstance(исходное, dict):
            ошибки.append(ОшибкаКарточки(номер, "карточка", "ожидается словарь", исходное))
            continue
        try:
            товар = нормализовать_товар(исходное)
        except ОшибкаНормализации as ошибка:
            причина = str(ошибка)
            поле = причина.split(":", 1)[0] if ":" in причина else "карточка"
            ошибки.append(ОшибкаКарточки(номер, поле, причина, исходное.copy()))
            continue
        предыдущий = идентификаторы.get(товар.внешний_идентификатор)
        if предыдущий is not None:
            ошибки.append(
                ОшибкаКарточки(
                    номер,
                    "external_id",
                    f"дубликат идентификатора; первая строка: {предыдущий}",
                    исходное.copy(),
                )
            )
            continue
        идентификаторы[товар.внешний_идентификатор] = номер
        успешные.append(УспешнаяКарточка(номер, товар, исходное.copy()))
    return РезультатПакета(всего, tuple(успешные), tuple(ошибки))
