"""Постраничное чтение товаров через существующие настройки подключения.

Не изменяет магазин. Алгоритм курсора требует подтверждения на реальном ответе API.
"""

from collections.abc import Iterator
from typing import Any

import httpx

from prom.подключения.подключение_prom import ПодключениеProm


class ОшибкаОбходаТоваров(RuntimeError):
    """Нельзя гарантировать полноту полученного каталога."""


class ИсточникТоваровProm:
    """Только GET: использует токен, настройки и транспорт существующего подключения."""

    def __init__(self, подключение: ПодключениеProm, размер_страницы: int = 100) -> None:
        if not 1 <= размер_страницы <= 100:
            raise ValueError("Размер страницы должен быть от 1 до 100")
        self.подключение = подключение
        self.размер_страницы = размер_страницы

    def страницы_товаров(self) -> Iterator[list[dict[str, Any]]]:
        настройки = self.подключение.настройки
        токен = self.подключение.хранилище.получить(настройки.имя_переменной_токена)
        курсор: int | None = None
        встреченные: set[int] = set()
        with httpx.Client(
            timeout=настройки.таймаут_секунд,
            transport=self.подключение._транспорт,
            follow_redirects=False,
            trust_env=False,
        ) as клиент:
            while True:
                параметры = {"limit": self.размер_страницы}
                if курсор is not None:
                    параметры["last_id"] = курсор
                ответ = клиент.get(
                    self.подключение.АДРЕС_ПРОВЕРКИ,
                    params=параметры,
                    headers={"Authorization": f"Bearer {токен}"},
                )
                ответ.raise_for_status()
                данные = ответ.json()
                if not isinstance(данные, dict) or not isinstance(данные.get("products"), list):
                    raise ОшибкаОбходаТоваров("Некорректная структура ответа списка")
                товары = данные["products"]
                if len(товары) > self.размер_страницы:
                    raise ОшибкаОбходаТоваров("Сервер вернул больше товаров, чем запрошено")
                if not товары:
                    return
                идентификаторы = []
                for товар in товары:
                    if (
                        not isinstance(товар, dict)
                        or type(товар.get("id")) is not int
                        or товар["id"] <= 0
                    ):
                        raise ОшибкаОбходаТоваров("Товар без корректного ID")
                    идентификаторы.append(товар["id"])
                if len(set(идентификаторы)) != len(идентификаторы) or any(
                    x in встреченные for x in идентификаторы
                ):
                    raise ОшибкаОбходаТоваров("Повтор товара между страницами")
                if курсор is not None and max(идентификаторы) >= курсор:
                    raise ОшибкаОбходаТоваров("Курсор не продвигается в сторону меньших ID")
                if идентификаторы != sorted(идентификаторы, reverse=True):
                    raise ОшибкаОбходаТоваров("Порядок ID не соответствует ожидаемой пагинации")
                встреченные.update(идентификаторы)
                yield товары
                if len(товары) < self.размер_страницы:
                    return
                курсор = идентификаторы[-1]
