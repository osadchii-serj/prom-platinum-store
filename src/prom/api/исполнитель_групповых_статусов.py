"""Проверки и журнал одного этапа группового изменения тестовых карточек."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any

import requests

from prom.api.статусы_товаров import АДРЕС_API, проверить_переход

ОЖИДАЕМЫЕ = {3243922294: 'PROM-TEST-20261022-001', 3244158641: 'PROM-TEST-20261022-002'}


class ОстановкаОперации(RuntimeError):
    """Вмешательство оператора обязательно."""


def проверить_план(план: Any) -> list[dict[str, Any]]:
    """Отвергнуть любой изменённый состав карточек и неподдерживаемый маршрут."""
    if not isinstance(план, dict) or not isinstance(план.get('карточки'), list):
        raise TypeError('Некорректный снимок')
    карточки = план['карточки']
    if len(карточки) != 2 or {к['идентификатор']: к['артикул'] for к in карточки} != ОЖИДАЕМЫЕ:
        raise ValueError('Разрешены только две закреплённые тестовые карточки')
    from prom.api.план_групповых_статусов import СнимокКарточки, построить_план

    ожидаемый = построить_план([СнимокКарточки(**к) for к in карточки])
    if план != ожидаемый:
        raise ValueError('План отличается от заново построенного; выполнение запрещено')
    for этап in план['этапы']:
        проверить_переход(этап['из'], этап['в'])
    return план['этапы']


def этапы_испытания(план: dict[str, Any]) -> list[dict[str, Any]]:
    """Свести два удаления в один POST, сохранив исходный план и его хеш."""
    исходные = проверить_план(план)
    удаление = [этап for этап in исходные if этап['этап'] in ('удаление_из_draft', 'удаление_скрытых')]
    if len(удаление) != 2:
        raise ОстановкаОперации('Ожидались два этапа удаления')
    запрос = [пункт for этап in удаление for пункт in этап['запрос']]
    if {пункт['id'] for пункт in запрос} != set(ОЖИДАЕМЫЕ) or len(запрос) != 2:
        raise ОстановкаОперации('Групповое удаление требует оба закреплённых ID')
    группа = {'этап': 'групповое_удаление', 'из': 'смешанные', 'в': 'deleted',
              'запрос': запрос,
              'исходные_статусы': {пункт['id']: этап['из'] for этап in удаление for пункт in этап['запрос']}}
    return [исходные[0], группа, *исходные[3:]]


def прочитать_журнал(путь: Path, сумма: str) -> list[dict[str, Any]]:
    if not путь.exists():
        return []
    записи = [json.loads(строка) for строка in путь.read_text(encoding='utf-8').splitlines()]
    if any(запись.get('сумма_плана') != сумма for запись in записи):
        raise ОстановкаОперации('Журнал относится к другому плану')
    if len(записи) % 2:
        raise ОстановкаОперации('Незавершённая операция: автоматический повтор запрещён')
    завершённые = []
    for номер in range(0, len(записи), 2):
        намерение, итог = записи[номер:номер + 2]
        if (намерение.get('состояние') != 'отправка_возможна'
            or итог.get('состояние') != 'подтверждено'
            or намерение.get('номер') != номер // 2
            or итог.get('номер') != номер // 2
            or намерение.get('этап') != итог.get('этап')):
            raise ОстановкаОперации('Журнал содержит незавершённый или неверный этап')
        завершённые.append(итог)
    return завершённые


def записать(путь: Path, запись: dict[str, Any]) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    with путь.open('a', encoding='utf-8') as файл:
        файл.write(json.dumps(запись, ensure_ascii=False, sort_keys=True) + '\n')
        файл.flush()
        os.fsync(файл.fileno())


def сверить_этап(соединение: requests.Session, этап: dict[str, Any], статус: str) -> None:
    """404 допустим исключительно для статуса deleted; прочие ответы сверяем по ID/SKU."""
    for пункт in этап['запрос']:
        идентификатор = пункт['id']
        ответ = соединение.get(f'{АДРЕС_API}/products/{идентификатор}', timeout=20)
        if статус == 'deleted' and ответ.status_code == 404:
            continue
        ответ.raise_for_status()
        данные = ответ.json()
        if not isinstance(данные, dict) or not isinstance(данные.get('product'), dict):
            raise TypeError('Неожиданная структура GET')
        товар = данные['product']
        if (товар.get('id'), товар.get('sku'), товар.get('status')) != (
            идентификатор, ОЖИДАЕМЫЕ[идентификатор], статус
        ):
            raise ОстановкаОперации(f'GET не подтвердил карточку {идентификатор}')


def выполнить_этап(
    план: dict[str, Any], путь_журнала: Path, соединение: requests.Session,
    токен_записи: str | None, подтверждение: str | None,
) -> tuple[int, dict[str, Any]]:
    """Не более одного POST; журнал намерения сохраняется до отправки."""
    этапы = этапы_испытания(план)
    сумма = hashlib.sha256(json.dumps(план, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    записи = прочитать_журнал(путь_журнала, сумма)
    номер = len(записи)
    if номер >= len(этапы):
        raise ОстановкаОперации('Все этапы уже подтверждены')
    этап = этапы[номер]
    if записи and записи[-1]['этап'] != этапы[номер - 1]['этап']:
        raise ОстановкаОперации('Нарушен порядок этапов')
    # Не считаем 404 доказательством удаления без собственного подтверждённого POST.
    if этап['из'] == 'deleted' and not any(
        запись['этап'] in ('групповое_удаление', 'удаление_из_draft', 'удаление_скрытых')
        for запись in записи
    ):
        raise ОстановкаОперации('Нет подтверждённого удаления в журнале')
    if этап['этап'] == 'групповое_удаление':
        for пункт in этап['запрос']:
            исходный = этап['исходные_статусы'][пункт['id']]
            проверить_переход(исходный, 'deleted')
            сверить_этап(соединение, {'запрос': [пункт]}, исходный)
    else:
        сверить_этап(соединение, этап, этап['из'])
    if подтверждение is None:
        return номер, этап
    if not токен_записи:
        raise ОстановкаОперации('Отсутствует токен записи')
    ожидаемая_фраза = f"ВЫПОЛНИТЬ {номер + 1} {этап['этап']}"
    if подтверждение != ожидаемая_фраза:
        raise ОстановкаОперации('Неверная фраза подтверждения')
    запись = {'сумма_плана': сумма, 'номер': номер, 'этап': этап['этап'],
              'состояние': 'отправка_возможна'}
    записать(путь_журнала, запись)
    # После этой точки никакой автоматический повтор недопустим.
    try:
        ответ = соединение.post(
            f'{АДРЕС_API}/products/edit',
            headers={'Authorization': f'Bearer {токен_записи}', 'Accept': 'application/json'},
            json=этап['запрос'], timeout=20,
        )
        ответ.raise_for_status()
        данные = ответ.json()
        ожидаемые_id = {пункт['id'] for пункт in этап['запрос']}
        if not isinstance(данные, dict) or данные.get('errors') or (
            not isinstance(данные.get('processed_ids'), list)
            or set(данные['processed_ids']) != ожидаемые_id
            or len(данные['processed_ids']) != len(ожидаемые_id)
        ):
            raise ОстановкаОперации('POST не подтвердил все ID без ошибок')
        сверить_этап(соединение, этап, этап['в'])
    except (requests.RequestException, ValueError, TypeError, ОстановкаОперации) as ошибка:
        raise ОстановкаОперации(
            'Результат неопределён. Повтор запрещён; журнал сохранён, нужна ручная сверка'
        ) from ошибка
    # Файл с исходным намерением остаётся неизменным; запись подтверждения отдельная.
    записать(путь_журнала, {'сумма_плана': сумма, 'номер': номер,
                             'этап': этап['этап'], 'состояние': 'подтверждено'})
    return номер, этап
