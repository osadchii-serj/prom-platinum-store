"""Извлечение контрактов товарных операций из официальной OpenAPI-спецификации."""

from __future__ import annotations

from pathlib import Path
from urllib.parse import urldefrag, urljoin

from prom.api.инвентаризация import АДРЕС_СПЕЦИФИКАЦИИ, загрузить_документы

МЕТОДЫ = frozenset({"post", "put", "patch", "delete"})


def разрешить_ссылку(документы: dict[str, dict], адрес: str, ссылка: str) -> tuple[object, str]:
    """Разрешить внешний либо внутренний $ref без сетевых запросов."""
    целевой, фрагмент = urldefrag(urljoin(адрес, ссылка))
    узел: object = документы[целевой]
    if фрагмент:
        if not фрагмент.startswith("/"):
            raise ValueError("Неподдерживаемый фрагмент ссылки")
        for часть in фрагмент[1:].split("/"):
            ключ = часть.replace("~1", "/").replace("~0", "~")
            if not isinstance(узел, dict):
                raise TypeError("Некорректная структура $ref")
            узел = узел[ключ]
    return узел, целевой


def описание_схемы(
    документы: dict[str, dict], адрес: str, схема: object, глубина: int = 0
) -> str:
    """Кратко описать схему без выдумывания полей и без бесконечной рекурсии."""
    if not isinstance(схема, dict):
        return "Схема отсутствует"
    if "$ref" in схема:
        ссылка = схема["$ref"]
        if глубина >= 2:
            return f"$ref: {ссылка}"
        узел, новый_адрес = разрешить_ссылку(документы, адрес, ссылка)
        return f"$ref: {ссылка}\n" + описание_схемы(
            документы, новый_адрес, узел, глубина + 1
        )
    строки = [f"Тип: {схема.get('type', 'не указан')}"]
    обязательные = схема.get("required", [])
    строки.append("Обязательные поля: " + (", ".join(map(str, обязательные)) or "не указаны"))
    свойства = схема.get("properties", {})
    if isinstance(свойства, dict):
        for имя, свойство in свойства.items():
            if isinstance(свойство, dict):
                тип = свойство.get("type", "")
                ссылка = свойство.get("$ref", "")
                элементы = свойство.get("items", {})
                if isinstance(элементы, dict) and элементы.get("$ref"):
                    ссылка = элементы["$ref"]
                строки.append(f"- `{имя}`: {тип or 'тип не указан'} {ссылка}".rstrip())
    for составной in ("allOf", "oneOf", "anyOf"):
        части = схема.get(составной)
        if isinstance(части, list):
            строки.append(f"{составной}:")
            for часть in части:
                описание = описание_схемы(документы, адрес, часть, глубина + 1)
                строки.append("  " + описание.replace("\n", "\n  "))
    return "\n".join(строки)


def сформировать_контракты(
    документы: dict[str, dict], адрес: str = АДРЕС_СПЕЦИФИКАЦИИ
) -> str:
    """Сформировать отчёт по потенциально изменяющим товарным методам."""
    корень = документы[адрес]
    пути = корень.get("paths", {})
    if not isinstance(пути, dict):
        raise TypeError("Поле paths должно быть объектом")
    строки = [
        "# Контракты изменения товаров Prom.ua",
        "",
        f"Источник: {адрес}",
        "",
        "Это описание спецификации, а не подтверждение возможности создания/удаления.",
        "Запросы к магазину НЕ выполнялись.",
        "",
    ]
    найдено = 0
    for путь, объект_пути in sorted(пути.items()):
        if not путь.startswith("/products/") or not isinstance(объект_пути, dict):
            continue
        # В официальном index.yaml ссылка относится ко всему Path Item,
        # а не непосредственно к HTTP-операции.
        адрес_пути = адрес
        if "$ref" in объект_пути:
            объект_пути, адрес_пути = разрешить_ссылку(
                документы, адрес, объект_пути["$ref"]
            )
        if not isinstance(объект_пути, dict):
            raise TypeError("Описание пути должно быть объектом")
        for метод, исходная_операция in объект_пути.items():
            if метод.lower() not in МЕТОДЫ or not isinstance(исходная_операция, dict):
                continue
            операция: object = исходная_операция
            адрес_операции = адрес_пути

            if "$ref" in исходная_операция:
                операция, адрес_операции = разрешить_ссылку(
                    документы, адрес_пути, исходная_операция["$ref"]
                )

            if not isinstance(операция, dict):
                raise TypeError("Описание операции должно быть объектом")
            найдено += 1
            строки.extend([
                f"## {метод.upper()} {путь}",
                "",
                f"Назначение: {операция.get('summary', 'не указано')}",
                f"Описание: {операция.get('description', 'не указано')}",
                "",
            ])
            тело = операция.get("requestBody")
            if isinstance(тело, dict) and "$ref" in тело:
                тело, адрес_тела = разрешить_ссылку(документы, адрес_операции, тело["$ref"])
            else:
                адрес_тела = адрес_операции
            if isinstance(тело, dict):
                строки.append(f"requestBody.required: {тело.get('required', False)}")
                содержимое = тело.get("content", {})
                if isinstance(содержимое, dict):
                    for формат, определение in содержимое.items():
                        строки.append(f"Формат: {формат}")
                        if isinstance(определение, dict):
                            строки.append("```")
                            строки.append(описание_схемы(
                                документы, адрес_тела, определение.get("schema")
                            ))
                            строки.append("```")
            else:
                строки.append("requestBody: не указан")
            ответы = операция.get("responses", {})
            if isinstance(ответы, dict):
                строки.append("Ответы: " + ", ".join(map(str, ответы)))
            строки.append("")
    if not найдено:
        raise ValueError("Операции изменения товаров не обнаружены")
    return "\n".join(строки) + "\n"


def выполнить(путь: Path) -> None:
    """Скачать только публичную спецификацию и сохранить отчёт."""
    документы = загрузить_документы()
    отчёт = сформировать_контракты(документы)
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(отчёт, encoding="utf-8")
