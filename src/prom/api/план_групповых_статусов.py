"""План группового испытания двух закреплённых тестовых карточек без POST."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any

from prom.api.статусы_товаров import проверить_переход


@dataclass(frozen=True)
class СнимокКарточки:
    идентификатор: int
    артикул: str
    исходный_статус: str


def извлечь_снимок(данные: Any, идентификатор: int, артикул: str) -> СнимокКарточки:
    """Проверить принадлежность ответа GET ожидаемой тестовой карточке."""
    if not isinstance(данные, dict) or not isinstance(данные.get("product"), dict):
        raise TypeError("GET не содержит объект product")
    товар = данные["product"]
    if товар.get("id") != идентификатор or товар.get("sku") != артикул:
        raise ValueError("ID/SKU не совпадают с ожидаемой тестовой карточкой")
    статус = товар.get("status")
    if not isinstance(статус, str):
        raise TypeError("Неизвестный статус карточки")
    return СнимокКарточки(идентификатор, артикул, статус)


def построить_план(карточки: list[СнимокКарточки]) -> dict[str, Any]:
    """Построить только план; переходы сверяются с подтверждённым контрактом."""
    if len(карточки) != 2 or len({к.идентификатор for к in карточки}) != 2:
        raise ValueError("План допускает ровно две разные карточки")
    ожидаемые = {
        "PROM-TEST-20261022-001": 3243922294,
        "PROM-TEST-20261022-002": 3244158641,
    }
    if {к.артикул: к.идентификатор for к in карточки} != ожидаемые:
        raise ValueError("План допускает только два закреплённых ID/SKU")
    if any(к.исходный_статус not in {"draft", "not_on_display", "on_display"} for к in карточки):
        raise ValueError("Исходный статус не допускается для этого испытания")

    шаги: list[dict[str, Any]] = []
    # Публикация не удаляется напрямую: сначала переводим её в draft.
    этапы = (
        ("подготовка_к_удалению", "on_display", "draft"),
        ("удаление_из_draft", "draft", "deleted"),
        ("удаление_скрытых", "not_on_display", "deleted"),
        ("восстановление", "deleted", "not_on_display"),
        ("возврат_черновиков", "not_on_display", "draft"),
        ("возврат_публикации", "draft", "on_display"),
    )
    маршруты = {
        "draft": ("удаление_из_draft", "восстановление", "возврат_черновиков"),
        "not_on_display": ("удаление_скрытых", "восстановление"),
        "on_display": (
            "подготовка_к_удалению", "удаление_из_draft", "восстановление",
            "возврат_черновиков", "возврат_публикации",
        ),
    }
    for имя, исходный, целевой in этапы:
        выбранные = [к for к in карточки if имя in маршруты[к.исходный_статус]]
        if not выбранные:
            continue
        проверить_переход(исходный, целевой)
        шаги.append({
            "этап": имя,
            "из": исходный,
            "в": целевой,
            "запрос": [{"id": к.идентификатор, "status": целевой} for к in выбранные],
        })
    return {
        "режим": "ТОЛЬКО_ПРОСМОТР_БЕЗ_POST",
        "карточки": [asdict(к) for к in карточки],
        "этапы": шаги,
        "предупреждение": (
            "Возврат публикации запланирован, но после реального удаления "
            "ещё не проверен. План не является разрешением на POST."
        ),
    }
