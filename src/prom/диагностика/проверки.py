"""Минимальные чистые проверки для начала разработки."""


def уникальные_идентификаторы(товары: list[dict]) -> bool:
    """Проверить отсутствие повторов целочисленных идентификаторов."""
    идентификаторы = [товар.get("id") for товар in товары]
    return all(type(значение) is int for значение in идентификаторы) and (
        len(идентификаторы) == len(set(идентификаторы))
    )
