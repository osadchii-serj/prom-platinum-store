"""Консольный сценарий сохранения и сравнения снимков каталога."""

from __future__ import annotations

import argparse
from pathlib import Path

from rich.console import Console

from prom.сценарии.хранилище_снимков import (
    показать_сохранённую_сверку,
    снять_и_сохранить,
)


def main() -> None:
    """Только чтение каталога и запись локальных JSON; без изменения товаров."""
    парсер = argparse.ArgumentParser(description="PROM: снимки каталога (только GET)")
    парсер.add_argument("действие", choices=("до", "после", "сверка"))
    парсер.add_argument("операция", help="Уникальный ключ операции (латиница, цифры, -_)")
    парсер.add_argument(
        "--каталог", type=Path, default=Path("data/снимки_каталога"),
        help="Локальный каталог для JSON-снимков",
    )
    аргументы = парсер.parse_args()
    вывод = Console()
    if аргументы.действие == "сверка":
        показать_сохранённую_сверку(
            аргументы.каталог, аргументы.операция, консоль=вывод,
        )
    else:
        путь = снять_и_сохранить(
            аргументы.каталог, аргументы.операция,
            аргументы.действие, консоль=вывод,
        )
        вывод.print(f"[green]Снимок сохранён:[/green] {путь}")
        вывод.print("[yellow]Изменение товаров запрещено[/yellow]")


if __name__ == "__main__":
    main()
