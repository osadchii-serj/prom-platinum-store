"""Консервативная привязка журнала импорта к снимкам каталога (только чтение)."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from rich.console import Console
from rich.table import Table

from prom.api.результаты_импорта import ЗаписьИмпорта, прочитать_запись
from prom.сценарии.сверка_каталога import Сверка
from prom.сценарии.хранилище_снимков import (
    прочитать_снимок,
    путь_снимка,
    сверить_сохранённые,
)


@dataclass(frozen=True)
class ОтчётОперации:
    """Результат проверки связи; автоматические изменения всегда запрещены."""

    запись: ЗаписьИмпорта
    сверка: Сверка
    предупреждения: tuple[str, ...]
    связь_подтверждена: bool
    разрешено_изменение: bool = False


def _время(строка: str) -> datetime:
    try:
        значение = datetime.fromisoformat(строка)
    except ValueError as ошибка:
        raise ValueError("Некорректная дата журнала или снимка") from ошибка
    if значение.tzinfo is None or значение.utcoffset() is None:
        raise ValueError("Время журнала или снимка должно иметь часовой пояс")
    return значение


def проверить_операцию(
    каталог_снимков: Path,
    путь_журнала: Path,
    ключ: str,
) -> ОтчётОперации:
    """Сверить принадлежность, целостность, порядок и состояние импорта."""
    # Проверка ключа выполняется до чтения любого файла.
    путь_снимка(каталог_снимков, ключ, "до")
    запись = прочитать_запись(путь_журнала)
    if запись.ключ != ключ:
        raise ValueError("Ключ журнала отличается от ключа снимков")
    до, метаданные_до = прочитать_снимок(каталог_снимков, ключ, "до")
    после, метаданные_после = прочитать_снимок(каталог_снимков, ключ, "после")
    сверка = сверить_сохранённые(каталог_снимков, ключ)
    предупреждения = list(сверка.предупреждения)
    связь_подтверждена = True

    if запись.состояние != "завершено":
        предупреждения.append("Операция импорта не имеет подтверждённого завершения")
        связь_подтверждена = False
    if запись.статус_api != "SUCCESS":
        предупреждения.append("Статус импорта не SUCCESS")
        связь_подтверждена = False
    идентификатор = запись.идентификатор_импорта
    if (
        идентификатор is None
        or not идентификатор.isascii()
        or not идентификатор.isdecimal()
        or int(идентификатор) <= 0
    ):
        предупреждения.append("В журнале нет корректного числового ID импорта")
        связь_подтверждена = False

    if not запись.обновлено_utc:
        предупреждения.append("В журнале отсутствует время последнего обновления")
        связь_подтверждена = False
    else:
        момент_до = _время(метаданные_до.создан_utc)
        момент_после = _время(метаданные_после.создан_utc)
        момент_журнала = _время(запись.обновлено_utc)
        if not момент_до < момент_журнала < момент_после:
            предупреждения.append(
                "Время журнала не находится строго между снимками до и после"
            )
            связь_подтверждена = False

    if not до.полный or not после.полный:
        предупреждения.append("Обнаружен неполный снимок")
        связь_подтверждена = False
    if сверка.удалённые_id:
        предупреждения.append("После импорта обнаружены исчезнувшие ID")
        связь_подтверждена = False
    if сверка.изменённые_id:
        предупреждения.append("После импорта изменились атрибуты существующих ID")
    предупреждения.append(
        "Новые ID не доказывают принадлежность импорту: возможны параллельные изменения"
    )
    return ОтчётОперации(
        запись, сверка, tuple(dict.fromkeys(предупреждения)), связь_подтверждена
    )


def показать_операцию(
    отчёт: ОтчётОперации, *, консоль: Console | None = None,
) -> None:
    """Вывести Rich-отчёт без SKU, URL поставщиков и токенов."""
    вывод = консоль if консоль is not None else Console()
    таблица = Table(title="PROM / связь импорта и снимков")
    таблица.add_column("Показатель")
    таблица.add_column("Значение")
    таблица.add_row("Ключ операции", отчёт.запись.ключ)
    таблица.add_row("Состояние журнала", отчёт.запись.состояние)
    таблица.add_row("Статус API", отчёт.запись.статус_api or "неизвестен")
    таблица.add_row("Новые ID (кандидаты)", str(len(отчёт.сверка.новые_id)))
    таблица.add_row("Исчезнувшие ID", str(len(отчёт.сверка.удалённые_id)))
    таблица.add_row("Изменённые ID", str(len(отчёт.сверка.изменённые_id)))
    таблица.add_row(
        "Проверки связи",
        "Пройдены" if отчёт.связь_подтверждена else "Есть препятствия",
    )
    таблица.add_row("Изменение товаров", "ЗАПРЕЩЕНО")
    вывод.print(таблица)
    for предупреждение in отчёт.предупреждения:
        вывод.print(f"[yellow]Внимание:[/yellow] {предупреждение}")


def main() -> None:
    """Запускать только локальную проверку; сетевых запросов нет."""
    парсер = argparse.ArgumentParser(description="PROM: сверка журнала и снимков")
    парсер.add_argument("ключ", help="Ключ операции, общий для журнала и снимков")
    парсер.add_argument("--журнал", required=True, type=Path)
    парсер.add_argument(
        "--снимки", type=Path, default=Path("data/снимки_каталога")
    )
    аргументы = парсер.parse_args()
    показать_операцию(
        проверить_операцию(аргументы.снимки, аргументы.журнал, аргументы.ключ)
    )


if __name__ == "__main__":
    main()
