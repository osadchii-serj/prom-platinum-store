"""Получение секретов из окружения без журналирования значений."""

import os


class ХранилищеПеременныхОкружения:
    def получить(self, имя_переменной: str) -> str:
        токен = os.getenv(имя_переменной, "").strip()
        if not токен:
            raise ValueError("Токен подключения не задан в окружении")
        return токен
